// Measures when each hit in a finished song is actually audible and writes src/episodes/<slug>/songMap.ts.
// The song comes first: the animation reads this map, so its hits follow the sound and not the other way round.
// Usage: npm run song-map <slug>
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { audioPath, loadMeta, requireSlug, ROOT } from "./lib/episode";

const WINDOW_S = 0.005;
const SCAN_S = 0.12;
/** A hit counts as audible once it is within this many dB of its own peak. */
const AUDIBLE_DB = 6;

const slug = requireSlug(process.argv[2], "npm run song-map <slug>");
const wavPath = audioPath(slug);
if (!existsSync(wavPath)) {
  console.error(`${path.relative(ROOT, wavPath)} not found. Run: npm run audio ${slug}`);
  process.exit(2);
}
const songPath = path.join(ROOT, "src/episodes", slug, "song.ts");
if (!existsSync(songPath)) {
  console.error(`src/episodes/${slug}/song.ts not found: it must export KICKS (and optionally STABS), in seconds.`);
  process.exit(2);
}
const { KICKS, STABS = [] } = (await import(pathToFileURL(songPath).href)) as { KICKS: number[]; STABS?: number[] };
const { fps } = await loadMeta(slug);

const wav = readFileSync(wavPath);
const sampleRate = wav.readUInt32LE(24);
const frames = (wav.length - 44) / 4;
const mono = (i: number) => (wav.readInt16LE(44 + i * 4) + wav.readInt16LE(46 + i * 4)) / 65536;

const rmsAt = (t: number) => {
  const from = Math.round(t * sampleRate);
  const n = Math.round(WINDOW_S * sampleRate);
  let sum = 0;
  for (let i = from; i < Math.min(frames, from + n); i++) sum += mono(i) ** 2;
  return Math.sqrt(sum / n);
};

/** Seconds from the scheduled hit until the sound reaches its audible level. */
const audibleDelay = (t: number) => {
  const STEP = 0.001;
  const levels: number[] = [];
  for (let d = 0; d < SCAN_S; d += STEP) levels.push(rmsAt(t + d));
  const threshold = Math.max(...levels) * 10 ** (-AUDIBLE_DB / 20);
  return levels.findIndex((l) => l >= threshold) * STEP;
};

// Picture hits land on whole frames. A hit that is late by under half a frame stays on its grid frame;
// otherwise it takes the first frame at or after the sound, because a picture that leads its sound reads as out of sync.
const placeHit = (t: number) => {
  const delay = audibleDelay(t);
  const frame = delay < 0.5 / fps ? Math.round(t * fps) : Math.ceil((t + delay) * fps);
  return { t, delayMs: delay * 1000, frame };
};

const kicks = KICKS.map(placeHit);
const stabs = STABS.map(placeHit);
const moved = [...kicks, ...stabs].filter((h) => h.frame !== Math.round(h.t * fps));
const sha = createHash("sha256").update(wav).digest("hex");

const list = (hits: { frame: number }[]) => `[${hits.map((h) => h.frame).join(", ")}]`;
const out = path.join(ROOT, "src/episodes", slug, "songMap.ts");
writeFileSync(
  out,
  `// Generated by \`npm run song-map ${slug}\` from public/${slug}/audio.wav. Do not edit by hand.
export const SONG_MAP = {
  wavSha256: "${sha}",
  fps: ${fps},
  /** Video frame on which each kick is first audible. */
  kickFrames: ${list(kicks)},
  /** Video frame on which each stab is first audible. */
  stabFrames: ${list(stabs)},
};
`,
);
console.log(`wrote ${path.relative(ROOT, out)}: ${kicks.length} kicks, ${stabs.length} stabs, ${moved.length} moved off the grid`);
for (const h of moved) console.log(`  hit at ${h.t.toFixed(3)} s is audible ${h.delayMs.toFixed(0)} ms late: picture hit on frame ${h.frame}`);
